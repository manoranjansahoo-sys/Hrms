from django.db import models
from django.conf import settings
from decimal import Decimal
from employees.models import EmployeeProfile


class SalaryStructure(models.Model):
    employee = models.OneToOneField(EmployeeProfile, on_delete=models.CASCADE, related_name='salary_structure')
    basic_salary = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    hra = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'), help_text="House Rent Allowance")
    conveyance_allowance = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    medical_allowance = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    special_allowance = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))

    # Standard deductions
    provident_fund = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'), help_text="PF Employee Contribution")
    professional_tax = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('200.00'))
    tds = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'), help_text="Tax Deducted at Source")

    is_active = models.BooleanField(default=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['employee']

    def __str__(self):
        return f"Salary Structure for {self.employee.emp_id} (Net: ₹{self.net_salary:,.2f})"

    @property
    def gross_salary(self):
        return (
            self.basic_salary +
            self.hra +
            self.conveyance_allowance +
            self.medical_allowance +
            self.special_allowance
        )

    @property
    def total_deductions(self):
        return (
            self.provident_fund +
            self.professional_tax +
            self.tds
        )

    @property
    def net_salary(self):
        return max(Decimal('0.00'), self.gross_salary - self.total_deductions)


class PayrollPeriod(models.Model):
    STATUS_CHOICES = [
        ('DRAFT', 'Draft (Generated by HR)'),
        ('SUBMITTED', 'Submitted for Head Approval'),
        ('APPROVED', 'Approved by Head / Super Admin'),
        ('PAID', 'Disbursed / Paid'),
    ]

    MONTH_NAMES = [
        (1, 'January'), (2, 'February'), (3, 'March'), (4, 'April'),
        (5, 'May'), (6, 'June'), (7, 'July'), (8, 'August'),
        (9, 'September'), (10, 'October'), (11, 'November'), (12, 'December')
    ]

    month = models.PositiveSmallIntegerField(choices=MONTH_NAMES)
    year = models.PositiveIntegerField(default=2026)
    working_days = models.PositiveIntegerField(default=26)
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='DRAFT')

    total_gross = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal('0.00'))
    total_deductions = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal('0.00'))
    total_net = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal('0.00'))

    processed_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, related_name='processed_payrolls')
    approved_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True, related_name='approved_payrolls')

    processed_at = models.DateTimeField(auto_now_add=True)
    approved_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        unique_together = ('month', 'year')
        ordering = ['-year', '-month']

    def __str__(self):
        return f"Payroll {self.get_month_display()} {self.year} ({self.get_status_display()})"


class Payslip(models.Model):
    STATUS_CHOICES = [
        ('GENERATED', 'Generated'),
        ('APPROVED', 'Approved'),
        ('PAID', 'Disbursed'),
    ]

    payroll_period = models.ForeignKey(PayrollPeriod, on_delete=models.CASCADE, related_name='payslips')
    employee = models.ForeignKey(EmployeeProfile, on_delete=models.CASCADE, related_name='payslips')
    month = models.PositiveSmallIntegerField()
    year = models.PositiveIntegerField()

    total_working_days = models.DecimalField(max_digits=5, decimal_places=1, default=Decimal('26.0'))
    present_days = models.DecimalField(max_digits=5, decimal_places=1, default=Decimal('0.0'))
    paid_leaves = models.DecimalField(max_digits=5, decimal_places=1, default=Decimal('0.0'))
    loss_of_pay_days = models.DecimalField(max_digits=5, decimal_places=1, default=Decimal('0.0'))
    payable_days = models.DecimalField(max_digits=5, decimal_places=1, default=Decimal('26.0'))

    # Earnings
    basic_salary = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    hra = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    conveyance_allowance = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    medical_allowance = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    special_allowance = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    bonus = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    gross_earnings = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))

    # Deductions
    provident_fund = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    professional_tax = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    tds = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    other_deductions = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    total_deductions = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))

    net_payable = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='GENERATED')
    payment_date = models.DateField(null=True, blank=True)
    payment_method = models.CharField(max_length=50, default='DIRECT_BANK_TRANSFER')
    transaction_ref = models.CharField(max_length=100, blank=True)
    generated_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        unique_together = ('payroll_period', 'employee')
        ordering = ['employee']

    def __str__(self):
        return f"Payslip - {self.employee.emp_id} - {self.month}/{self.year} (₹{self.net_payable:,.2f})"
